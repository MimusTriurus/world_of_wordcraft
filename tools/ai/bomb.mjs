// Порог бомбы: правило игры или частность одной политики?
//
// В коде игры бомбе назначена роль ответа на ДАВЛЕНИЕ: «подсказка выручает
// знание, бомба от давления на поле, снаряд платит за отказ от слова». Бот
// нашёл, что при пороге «жду трёх горящих блоков разом» бомба не тратится ни
// разу за забег, а при пороге в один горящий блок становится лучшей политикой.
// Если это держится на всех классах и не зависит от щедрости раздачи, то роль
// бомбы описана в коде неверно: она работает как снаряд, который заодно чистит
// поле.
//
//   node tools/ai/bomb.mjs [сидов]
import { table } from "./run.mjs";
import { CLASS_NAMES } from "./player.mjs";

const seeds = +(process.argv[2] || 12);
const THRESHOLDS = [1, 2, 3, 4, false];

console.log(`${seeds} сидов на клетку\n`);
console.log("порог — сколько блоков у линии оправдывают бомбу; false — не бомбить");

for (const cls of CLASS_NAMES) {
  const rows = THRESHOLDS.map(bomb => {
    const r = table(seeds, [cls], { policy: { bomb } })[0];
    return { порог: bomb === false ? "не бомбить" : bomb,
             круг: r.круг, решено: r.решено, очки: r.очки,
             "бомб потрачено": r.бомбы, "снарядов потрачено": r.снаряды };
  });
  console.log(`\n${cls}`);
  console.table(rows);
}

// Не в щедрости ли раздачи дело: бомб дают +1 за границу, снарядов +3.
// Если бомба сильна только потому, что её берут вместо трёх снарядов, то при
// раздаче «всегда снаряды» преимущество низкого порога должно исчезнуть.
console.log("\nтот же порог при раздаче «всегда снаряды» (бомбы приходят только за круг)");
const rows = [];
for (const cls of CLASS_NAMES)
  for (const bomb of [1, 3, false]) {
    const r = table(seeds, [cls], { policy: { bomb, draft: "shells" } })[0];
    rows.push({ класс: cls, порог: bomb === false ? "не бомбить" : bomb,
                круг: r.круг, решено: r.решено, "бомб потрачено": r.бомбы });
  }
console.table(rows);
