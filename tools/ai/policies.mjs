// Сравнение политик траты. Это то, на что прежний модельный игрок ответить не
// мог вовсе: он не брал в руки ни бомбу, ни подсказку, так что о ценности
// выбора между слотами раздачи не говорил ничего.
//
//   node tools/ai/policies.mjs [сидов] [класс]
import { table } from "./run.mjs";

const seeds = +(process.argv[2] || 16);
const cls = process.argv[3] || "средний";

// Выключая кошелёк, выключаем и его строку в раздаче: иначе он наказывает
// дважды — стрелять нельзя и выбор съеден. Об это спотыкнулась первая версия
// этой таблицы, и «без подсказок» вышло вдвое хуже, чем есть.
const CASES = [
  ["всё включено",        {}],
  ["без подсказок",       { hint: false }],
  ["без снарядов",        { shell: false }],
  ["без бомб",            { bomb: false }],
  ["без догадок",         { guess: false }],
  ["только снаряды (как прежняя модель)",
                          { hint: false, guess: false, bomb: false, draft: "shells" }],
  ["бомба от 2 блоков",   { bomb: 2 }],
  ["бомба от 1 блока",    { bomb: 1 }],
  ["раздача: снаряды",    { draft: "shells" }],
  ["раздача: бомбы",      { draft: "bombs" }],
  ["раздача: подсказки",  { draft: "tips" }],
];

console.log(`${cls}, ${seeds} сидов на строку`);
const rows = [];
for (const [name, policy] of CASES) {
  const r = table(seeds, [cls], { policy })[0];
  rows.push({ политика: name, круг: r.круг, решено: r.решено, очки: r.очки,
              снаряды: r.снаряды, бомбы: r.бомбы, подсказки: r.подсказки,
              "безнадёжных": r["безнадёжных"] });
}
console.table(rows);
console.log("\nРазницу меньше нескольких процентов на такой выборке от шума " +
            "не отличить, и выдавать её за результат нельзя.");
